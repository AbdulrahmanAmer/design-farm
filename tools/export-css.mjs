#!/usr/bin/env node
/**
 * export-css.mjs — flatten the farm's tokens into one self-contained CSS file
 * for projects that can't import the farm (static HTML pages, other stacks).
 *
 *   node tools/export-css.mjs > out.css
 *   node tools/export-css.mjs --fonts --dark violet-night --out ../site/theme.tokens.css
 *
 * --fonts         prepend the Google Fonts @import for every type facet (must stay first in a stylesheet)
 * --dark <id>     also apply palette <id> when the page asks for dark without choosing a palette:
 *                 prefers-color-scheme: dark (unless [data-theme="light"]) and [data-theme="dark"].
 *                 Needs no JS, and keeps host pages that toggle data-theme working.
 * --strip         drop comments
 * --out <file>    write to a file instead of stdout
 *
 * The output keeps every facet, so data-palette / data-depth / data-shape / data-type /
 * data-density attributes still remix the page at runtime.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const args = process.argv.slice(2);
const has = (f) => args.includes(`--${f}`);
const val = (f) => (args.includes(`--${f}`) ? args[args.indexOf(`--${f}`) + 1] : undefined);

const FONTS =
  '@import url("https://fonts.googleapis.com/css2?family=Manrope:wght@400;500;600;700&family=Urbanist:wght@400;500;600;700&display=swap");';

function inline(file, seen = new Set()) {
  const abs = resolve(file);
  if (seen.has(abs)) return "";
  seen.add(abs);
  return readFileSync(abs, "utf8").replace(/@import\s+"([^"]+)";/g, (_, rel) => inline(resolve(dirname(abs), rel), seen));
}

/** Body of the block whose selector list contains [data-palette="<id>"]. */
function paletteBody(css, id) {
  const m = css.match(new RegExp(`\\[data-palette="${id}"\\]\\s*\\{([\\s\\S]*?)\\n\\}`));
  if (!m) throw new Error(`palette "${id}" not found in tokens`);
  return m[1];
}

let css = inline(resolve(root, "tokens/index.css"));
if (has("strip")) css = css.replace(/\/\*[\s\S]*?\*\//g, "").replace(/\n{3,}/g, "\n\n");

const dark = val("dark");
if (dark) {
  const body = paletteBody(css, dark);
  css +=
    `\n/* --dark ${dark}: dark mode without choosing a palette */\n` +
    `:root[data-theme="dark"]:not([data-palette]) {${body}\n}\n` +
    `@media (prefers-color-scheme: dark) {\n  :root:not([data-theme="light"]):not([data-palette]) {${body}\n  }\n}\n`;
}

const sha = (() => {
  try {
    const head = readFileSync(resolve(root, ".git/HEAD"), "utf8").trim();
    const ref = head.startsWith("ref:") ? readFileSync(resolve(root, ".git", head.slice(5)), "utf8").trim() : head;
    return ref.slice(0, 7);
  } catch {
    return "unknown";
  }
})();

const out =
  (has("fonts") ? FONTS + "\n" : "") +
  `/* design-farm tokens @ ${sha} — generated by design-farm/tools/export-css.mjs; do not edit by hand */\n` +
  css.trim() +
  "\n";

const target = val("out");
if (target) {
  writeFileSync(target, out);
  console.error(`wrote ${target} (${out.length} bytes)`);
} else {
  process.stdout.write(out);
}
